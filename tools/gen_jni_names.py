import re, sys

src = open('port/third_party/ndk/jni.h', encoding='utf-8', errors='replace').read()

idx = src.find('struct JNINativeInterface_')
while idx != -1:
    brace = src.find('{', idx)
    if brace != -1 and brace - idx < 120:
        break
    idx = src.find('struct JNINativeInterface_', idx + 1)

if idx == -1:
    raise SystemExit('struct not found')

# brace matching
depth = 0
end = -1
for i in range(brace, len(src)):
    if src[i] == '{':
        depth += 1
    elif src[i] == '}':
        depth -= 1
        if depth == 0:
            end = i
            break
body = src[brace + 1:end]

names = []
for line in body.split('\n'):
    line = line.strip()
    if not line or line.startswith('//') or line.startswith('/*') or line.startswith('*'):
        continue
    fm = re.search(r'\(\s*JNICALL\s*\*\s*(\w+)\s*\)', line)
    if fm:
        names.append(fm.group(1))
        continue
    pm = re.search(r'\*\s*(\w+)\s*;', line)
    if pm:
        names.append(pm.group(1))

print('fields:', len(names))
print('first:', names[:5])
print('last:', names[-3:])
# JDK 21 appends GetModule/IsVirtualThread (not present on Android): truncate
if 'GetObjectRefType' in names:
    names = names[:names.index('GetObjectRefType') + 1]
print('android fields:', len(names))
assert names[4] == 'GetVersion' and names[-1] == 'GetObjectRefType', 'unexpected layout'

out = ['// generated by tools/gen_jni_names.py from jni.h',
       '#pragma once',
       'namespace sjf {',
       'static const char* kJNINativeInterfaceNames[] = {']
for n in names:
    out.append('    "%s",' % n)
out.append('};')
out.append('static constexpr unsigned kJNINativeInterfaceCount = %d;' % len(names))
out.append('} // namespace sjf')
open('port/src/dex/jni_table_names.h', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote port/src/dex/jni_table_names.h')
